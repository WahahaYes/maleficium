fn validator() -> Result<jsonschema::Validator, String> {
    let schema: Value = serde_json::from_str(MANIFEST_SCHEMA)
        .map_err(|e| format!("the committed manifest schema is not json: {e}"))?;
    jsonschema::validator_for(&schema).map_err(|e| format!("the manifest schema is invalid: {e}"))
}

/// Checks a manifest against the committed schema and the invariants the
/// schema cannot express. Every violation is named.
pub fn validate_manifest(m: &Value) -> Result<(), String> {
    // paper.reader: closed shapes with named errors (the schema repeats
    // them). Absent means a bundle from before flags existed: still valid.
    // A boolean is strict: no number or string coerces to it.
    let reader = &m["paper"]["reader"];
    if !reader.is_null() {
        let obj = reader
            .as_object()
            .ok_or_else(|| "paper.reader is not an object".to_string())?;
        if !obj.get("contents").is_some_and(Value::is_boolean) {
            return Err("paper.reader.contents is not a boolean".to_string());
        }
        if !obj
            .get("measure")
            .and_then(Value::as_str)
            .is_some_and(|s| matches!(s, "narrow" | "default" | "wide"))
        {
            return Err("paper.reader.measure is not narrow, default or wide".to_string());
        }
    }
    let v = validator()?;
    let errors: Vec<String> = v
        .iter_errors(m)
        .map(|e| format!("{} at {}", e, e.instance_path()))
        .collect();
    if !errors.is_empty() {
        return Err(format!(
            "the manifest breaks its schema: {}",
            errors.join("; ")
        ));
    }
    let widgets = m["widgets"].as_array().cloned().unwrap_or_default();
    let assets = m["assets"].as_object().cloned().unwrap_or_default();
    let pages = m["pdf"]["pages"].as_u64().unwrap_or(0);
    let profile = m.get("profile").and_then(Value::as_str).unwrap_or("folder");
    let mut ids = BTreeSet::new();
    let mut last: Option<(u64, f64)> = None;
    for w in &widgets {
        let id = w["id"].as_str().unwrap_or("");
        if !ids.insert(id.to_string()) {
            return Err(format!("widget id `{id}` appears twice"));
        }
        let refs = std::iter::once(w["poster"].as_str()).chain(
            w.get("sources")
                .and_then(Value::as_object)
                .into_iter()
                .flat_map(|s| s.values().map(Value::as_str)),
        );
        for r in refs {
            let r = r.unwrap_or("");
            if !assets.contains_key(r) {
                return Err(format!(
                    "widget {id} names asset `{r}`, which does not exist"
                ));
            }
        }
        let page = w["page"].as_u64().unwrap_or(0);
        if page > pages {
            return Err(format!("widget {id} is on page {page} of {pages}"));
        }
        let r: Vec<f64> = w["rect"]
            .as_array()
            .map(|a| a.iter().filter_map(Value::as_f64).collect())
            .unwrap_or_default();
        if r.len() != 4 || r[0] >= r[2] || r[1] >= r[3] {
            return Err(format!("widget {id} has a rect that is not x0<x1, y0<y1"));
        }
        // Document order: page, then top to bottom.
        let top = r[3];
        if let Some((lp, lt)) = last {
            if page < lp || (page == lp && top > lt) {
                return Err(format!("widget {id} is out of document order"));
            }
        }
        last = Some((page, top));
        if profile == "single-file" && w.get("entry").is_some() {
            return Err(format!("widget {id} has an entry in a single-file bundle"));
        }
    }
    // Custom runtimes: every live widget's runtime is listed and every
    // listed runtime is run by a live widget; a listed runtime's name and
    // major match its ref; a fallback widget carries nothing to run; no
    // custom widget declares origins.
    let runtimes = m["runtimes"].as_object().cloned().unwrap_or_default();
    let mut used = BTreeSet::new();
    for w in widgets.iter().filter(|w| w["type"] == "custom") {
        let id = w["id"].as_str().unwrap_or("");
        let r = w["runtime"].as_str().unwrap_or("");
        if w.get("csp").is_some() {
            return Err(format!("custom widget {id} declares a csp"));
        }
        if w.get("fallback").is_some() {
            let empty = w["sources"].as_object().is_some_and(|s| s.is_empty());
            if !empty || w.get("entry").is_some() || w.get("options").is_some() {
                return Err(format!(
                    "widget {id} falls back to its poster but carries sources, an entry or options"
                ));
            }
        } else if !runtimes.contains_key(r) {
            return Err(format!(
                "widget {id} runs runtime {r}, which the manifest does not list"
            ));
        } else {
            used.insert(r.to_string());
        }
    }
    for (r, e) in &runtimes {
        if !used.contains(r) {
            return Err(format!("runtime {r} is listed but no live widget runs it"));
        }
        let major = e["version"]
            .as_str()
            .and_then(|v| v.split('.').next())
            .unwrap_or("");
        let named = format!("{}@{major}", e["name"].as_str().unwrap_or(""));
        if !crate::runtimes::valid_ref(r) || named != *r {
            return Err(format!(
                "runtime {r} is listed as {named}, or names a reserved runtime"
            ));
        }
    }
    if profile == "single-file" {
        if assets.values().any(|a| a["mode"] == "bundled") {
            return Err("a single-file bundle has a bundled asset".to_string());
        }
        if !m["pdf"]["path"].is_null() {
            return Err("a single-file bundle must inline its pdf".to_string());
        }
    } else if m["pdf"]["path"] != "paper.pdf" {
        return Err("a folder or hosted bundle keeps its pdf at paper.pdf".to_string());
    }
    Ok(())
}

