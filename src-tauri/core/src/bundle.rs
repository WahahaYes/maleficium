fn validator() -> Result<jsonschema::Validator, String> {
    let schema: Value = serde_json::from_str(MANIFEST_SCHEMA)
        .map_err(|e| format!("the committed manifest schema is not json: {e}"))?;
    jsonschema::validator_for(&schema).map_err(|e| format!("the manifest schema is invalid: {e}"))
}

/// Checks a manifest against the committed schema and the invariants the
/// schema cannot express. Every violation is named.
pub fn validate_manifest(m: &Value) -> Result<(), String> {
    let v = validator()?;
    let errors: Vec<String> = v
        .iter_errors(m)
        .map(|e| format!("{} at {}", e, e.instance_path()))
        .collect();
    if !errors.is_empty() {
        return Err(format!(
            "the manifest breaks its schema: {}",
            errors.join("; ")
        ));
    }
    let widgets = m["widgets"].as_array().cloned().unwrap_or_default();
    let assets = m["assets"].as_object().cloned().unwrap_or_default();
    let pages = m["pdf"]["pages"].as_u64().unwrap_or(0);
    let profile = m.get("profile").and_then(Value::as_str).unwrap_or("folder");
    let mut ids = BTreeSet::new();
    let mut last: Option<(u64, f64)> = None;
    for w in &widgets {
        let id = w["id"].as_str().unwrap_or("");
        if !ids.insert(id.to_string()) {
            return Err(format!("widget id `{id}` appears twice"));
        }
        let refs = std::iter::once(w["poster"].as_str()).chain(
            w.get("sources")
                .and_then(Value::as_object)
                .into_iter()
                .flat_map(|s| s.values().map(Value::as_str)),
        );
        for r in refs {
            let r = r.unwrap_or("");
            if !assets.contains_key(r) {
                return Err(format!(
                    "widget {id} names asset `{r}`, which does not exist"
                ));
            }
        }
        let page = w["page"].as_u64().unwrap_or(0);
        if page > pages {
            return Err(format!("widget {id} is on page {page} of {pages}"));
        }
        let r: Vec<f64> = w["rect"]
            .as_array()
            .map(|a| a.iter().filter_map(Value::as_f64).collect())
            .unwrap_or_default();
        if r.len() != 4 || r[0] >= r[2] || r[1] >= r[3] {
            return Err(format!("widget {id} has a rect that is not x0<x1, y0<y1"));
        }
        // Document order: page, then top to bottom.
        let top = r[3];
        if let Some((lp, lt)) = last {
            if page < lp || (page == lp && top > lt) {
                return Err(format!("widget {id} is out of document order"));
            }
        }
        last = Some((page, top));
        if profile == "single-file" && w.get("entry").is_some() {
            return Err(format!("widget {id} has an entry in a single-file bundle"));
        }
    }
    if profile == "single-file" {
        if assets.values().any(|a| a["mode"] == "bundled") {
            return Err("a single-file bundle has a bundled asset".to_string());
        }
        if !m["pdf"]["path"].is_null() {
            return Err("a single-file bundle must inline its pdf".to_string());
        }
    } else if m["pdf"]["path"] != "paper.pdf" {
        return Err("a folder or hosted bundle keeps its pdf at paper.pdf".to_string());
    }
    Ok(())
}

// ---- writing ------------------------------------------------------------

/// Serializes JSON for a `<script type="application/json">` island: `<` is
/// escaped so no string can close the element.
fn island(id: &str, v: &Value) -> String {
    let s = serde_json::to_string(v)
        .unwrap_or_default()
        .replace('<', "\\u003c");
    format!("<script type=\"application/json\" id=\"{id}\">{s}</script>")
}

fn placeholder_reader(title: &str, authors: &[String], folder: bool, islands: &str) -> String {
    let policy = if folder {
        fold::FOLDER_READER_POLICY
    } else {
        fold::SINGLE_FILE_READER_POLICY
    };
    let pdf = if folder {
        "<p><a href=\"paper.pdf\">paper.pdf</a> is the version of record.</p>"
    } else {
        "<p>The version of record is embedded in this file.</p>"
    };
    let by = authors
        .iter()
        .filter(|a| !a.is_empty())
        .map(|a| fold::text(a))
        .collect::<Vec<_>>()
        .join(", ");
    let head = fold::with_policy(
        &format!(
            "<!doctype html><html lang=\"en\"><head><title>{0}</title></head><body><main><h1>{0}</h1><p>{by}</p><p>This bundle's reader is not part of this build. The manifest, the paper and every widget are complete.</p>{pdf}</main>",
            fold::text(title)
        ),
        policy,
    );
    format!("{head}{islands}</body></html>\n")
}

fn read_verified(path: &Path, sha: &str) -> Result<Vec<u8>, String> {
    let b = std::fs::read(path).map_err(|e| format!("cannot read {}: {e}", path.display()))?;
    if sha_of(&b) != sha {
        return Err(format!(
            "{} changed while it was being exported: run the export again",
            path.display()
        ));
    }
    Ok(b)
}

fn put(root: &Path, rel: &str, bytes: &[u8], total: &mut u64) -> Result<(), String> {
    let p = root.join(rel);
    if let Some(parent) = p.parent() {
        std::fs::create_dir_all(parent)
            .map_err(|e| format!("cannot create {}: {e}", parent.display()))?;
    }
    std::fs::File::create(&p)
        .and_then(|mut f| f.write_all(bytes))
        .map_err(|e| format!("cannot write {}: {e}", p.display()))?;
    *total += bytes.len() as u64;
    Ok(())
}

/// Whether `dir` holds an earlier bundle of ours (its manifest names the
/// format): the only non-empty folder an export replaces.
fn is_earlier_bundle(dir: &Path) -> bool {
    std::fs::read_to_string(dir.join("manifest.json"))
        .ok()
        .and_then(|t| serde_json::from_str::<Value>(&t).ok())
        .is_some_and(|v| v["format"] == FORMAT)
}

/// What an export may do at `dest` before anything is written.
fn check_destination(root: &Path, dest: &str, profile: BundleProfile) -> Result<PathBuf, String> {
    let out = crate::export::destination(root, dest)?;
    if root.starts_with(&out) {
        return Err(
            "export destination contains the project: choose a folder outside it".to_string(),
        );
    }
    match std::fs::symlink_metadata(&out) {
        Err(_) => {}
        Ok(m) if m.file_type().is_symlink() => {
            return Err(format!(
                "export destination is a symlink: {}",
                out.display()
            ));
        }
        Ok(m) => match profile {
            BundleProfile::SingleFile => {
                if m.is_dir() {
                    return Err(format!("export destination is a folder: {}", out.display()));
                }
            }
            _ => {
                if !m.is_dir() {
                    return Err(format!("export destination is a file: {}", out.display()));
                }
                let empty = std::fs::read_dir(&out)
                    .map_err(|e| format!("cannot list {}: {e}", out.display()))?
                    .next()
                    .is_none();
                if !empty && !is_earlier_bundle(&out) {
                    return Err(format!(
                        "export destination is not empty and is not an earlier bundle: {}",
                        out.display()
                    ));
                }
            }
        },
    }
    Ok(out)
}

fn staging_name(out: &Path) -> PathBuf {
    let name = out
        .file_name()
        .map(|n| n.to_string_lossy().to_string())
        .unwrap_or_default();
    out.with_file_name(format!(".{name}.mfw-partial-{}", std::process::id()))
}

/// Exports a paper bundle with no network and no approvals: the call the
/// automation surface makes.
pub fn export_bundle(
    cx: &Core,
    root_id: &str,
    main_rel: &str,
    dest: &str,
    profile: BundleProfile,
    size_cap_bytes: Option<u64>,
) -> Result<BundleExported, String> {
    export_bundle_with(
        cx,
        root_id,
        main_rel,
        dest,
        profile,
        &BundleOptions {
            size_cap_bytes,
            ..BundleOptions::default()
        },
    )
}

/// Exports a paper bundle of `main_rel`'s last compile to `dest`, outside the
/// project.
pub fn export_bundle_with(
    cx: &Core,
    root_id: &str,
    main_rel: &str,
    dest: &str,
    profile: BundleProfile,
    opts: &BundleOptions,
) -> Result<BundleExported, String> {
    let root = crate::fs::session_root(cx, root_id)?;
    let out = check_destination(&root, dest, profile)?;

    // The typed widget list is the join of sidecar and pdf; it also fails when
    // the main file was never compiled.
    let list = crate::widgets::widgets(cx, root_id, main_rel)?;
    let o = crate::outputs::outputs_of(cx, root_id, main_rel)?;
    let pdf_bytes = std::fs::read(o.outdir.join(&o.pdf_name))
        .map_err(|_| format!("{main_rel} has no compiled pdf: compile it first"))?;
    let pdf = hayro::hayro_syntax::Pdf::new(pdf_bytes.clone())
        .map_err(|e| format!("cannot read the pdf of {main_rel}: {e:?}"))?;
    let pages = pdf.pages().len() as u32;
    if pages == 0 || pdf_bytes.is_empty() {
        return Err(format!("the pdf of {main_rel} has no pages"));
    }

    let mut theme_ids: BTreeSet<&str> = list.widgets.iter().map(|w| w.theme.as_str()).collect();
    if theme_ids.is_empty() {
        theme_ids.insert("house");
    }
    if theme_ids.len() > 1 {
        return Err(format!(
            "the widgets name more than one theme ({}): the paper has one",
            theme_ids.iter().copied().collect::<Vec<_>>().join(", ")
        ));
    }
    let theme_id = theme_ids.into_iter().next().unwrap_or("house").to_string();
    if theme_id != "house" {
        return Err(format!(
            "theme `{theme_id}` is not available: only the built-in house theme is in this build"
        ));
    }

    let mut plan = Plan {
        cx,
        root_id,
        root: root.clone(),
        main_dir_rel: Path::new(main_rel)
            .parent()
            .map(Path::to_path_buf)
            .unwrap_or_default(),
        profile,
        opts,
        assets: BTreeMap::new(),
        warnings: Vec::new(),
    };

    let stem = o
        .main_file
        .strip_suffix(".tex")
        .unwrap_or(&o.main_file)
        .to_string();
    let tex = std::fs::read_to_string(root.join(&plan.main_dir_rel).join(&o.main_file))
        .map_err(|e| format!("cannot read {main_rel}: {e}"))?;
    let meta = paper_meta(&tex, &stem, &mut plan.warnings);

    let mut planned = Vec::new();
    for w in &list.widgets {
        planned.push(plan_widget(&mut plan, w, &pdf, pages)?);
    }

    let mut paper = Map::new();
    paper.insert("title".into(), meta.title.clone().into());
    paper.insert(
        "authors".into(),
        Value::Array(
            meta.authors
                .iter()
                .map(|(n, aff)| {
                    let mut a = Map::new();
                    a.insert("name".into(), n.clone().into());
                    if !aff.is_empty() {
                        a.insert("affiliations".into(), json!(aff));
                    }
                    Value::Object(a)
                })
                .collect(),
        ),
    );
    if let Some(a) = &meta.abstract_text {
        paper.insert("abstract".into(), a.clone().into());
    }
    let single = profile == BundleProfile::SingleFile;
    let cap = opts.size_cap_bytes.unwrap_or(DEFAULT_SIZE_CAP_BYTES);
    let mut manifest = Map::new();
    manifest.insert("format".into(), FORMAT.into());
    manifest.insert("formatVersion".into(), 1.into());
    manifest.insert(
        "generator".into(),
        json!({ "name": "maleficium", "version": env!("CARGO_PKG_VERSION") }),
    );
    manifest.insert(
        "profile".into(),
        serde_json::to_value(profile).map_err(|e| e.to_string())?,
    );
    if single {
        manifest.insert("sizeCapBytes".into(), cap.into());
    }
    manifest.insert("paper".into(), Value::Object(paper));
    manifest.insert(
        "pdf".into(),
        json!({
            "path": if single { Value::Null } else { "paper.pdf".into() },
            "sha256": sha_of(&pdf_bytes),
            "bytes": pdf_bytes.len(),
            "pages": pages
        }),
    );
    manifest.insert(
        "theme".into(),
        json!({ "id": theme_id, "contractVersion": CONTRACT_VERSION }),
    );
    manifest.insert(
        "widgets".into(),
        Value::Array(planned.iter().map(|p| p.json.clone()).collect()),
    );
    manifest.insert(
        "assets".into(),
        Value::Object(
            plan.assets
                .iter()
                .map(|(k, a)| (k.clone(), a.record()))
                .collect(),
        ),
    );
    let manifest = Value::Object(manifest);
    validate_manifest(&manifest)?;

    // Writing starts only now: every read, hash and check above has passed.
    let stage = staging_name(&out);
    let _ = std::fs::remove_dir_all(&stage);
    let _ = std::fs::remove_file(&stage);
    let mut total = 0u64;
    let manifest_text = serde_json::to_string_pretty(&manifest).map_err(|e| e.to_string())? + "\n";
    let authors: Vec<String> = meta.authors.iter().map(|a| a.0.clone()).collect();

    let written = (|| -> Result<(), String> {
        if single {
            let mut assets = Map::new();
            for a in plan.assets.values().filter(|a| a.mode == Mode::Inline) {
                if assets.contains_key(&a.sha) {
                    continue;
                }
                let bytes = match &a.data {
                    Bytes::File(p) => read_verified(p, &a.sha)?,
                    Bytes::Mem(b) => b.clone(),
                    Bytes::None => continue,
                };
                assets.insert(
                    a.sha.clone(),
                    base64::engine::general_purpose::STANDARD
                        .encode(bytes)
                        .into(),
                );
            }
            let widgets: Map<String, Value> = planned
                .iter()
                .map(|p| (p.id.clone(), p.doc.clone().into()))
                .collect();
            let islands = [
                island("mfw-manifest", &manifest),
                island("mfw-widgets", &Value::Object(widgets)),
                island("mfw-assets", &Value::Object(assets)),
                island(
                    "mfw-pdf",
                    &base64::engine::general_purpose::STANDARD
                        .encode(&pdf_bytes)
                        .into(),
                ),
            ]
            .concat();
            let html = placeholder_reader(&meta.title, &authors, false, &islands);
            std::fs::write(&stage, html.as_bytes())
                .map_err(|e| format!("cannot write {}: {e}", stage.display()))?;
            total = html.len() as u64;
        } else {
            std::fs::create_dir_all(&stage)
                .map_err(|e| format!("cannot create {}: {e}", stage.display()))?;
            put(
                &stage,
                "manifest.json",
                manifest_text.as_bytes(),
                &mut total,
            )?;
            put(&stage, "paper.pdf", &pdf_bytes, &mut total)?;
            put(
                &stage,
                "theme/theme.json",
                theme_json(&theme_id).as_bytes(),
                &mut total,
            )?;
            put(&stage, "theme/theme.css", THEME_CSS.as_bytes(), &mut total)?;
            for p in &planned {
                put(
                    &stage,
                    &format!("widgets/{}/index.html", p.id),
                    p.doc.as_bytes(),
                    &mut total,
                )?;
            }
            let mut inline = Map::new();
            let mut stored = BTreeSet::new();
            for a in plan.assets.values() {
                let bytes = match (&a.data, a.mode) {
                    (_, Mode::Remote) | (Bytes::None, _) => continue,
                    (Bytes::File(p), _) => read_verified(p, &a.sha)?,
                    (Bytes::Mem(b), _) => b.clone(),
                };
                if a.mode == Mode::Inline {
                    inline.insert(
                        a.sha.clone(),
                        base64::engine::general_purpose::STANDARD
                            .encode(&bytes)
                            .into(),
                    );
                } else if stored.insert(a.path()) {
                    put(&stage, &a.path(), &bytes, &mut total)?;
                }
            }
            let islands = [
                island("mfw-manifest", &manifest),
                if inline.is_empty() {
                    String::new()
                } else {
                    island("mfw-assets", &Value::Object(inline))
                },
            ]
            .concat();
            let html = placeholder_reader(&meta.title, &authors, true, &islands);
            put(&stage, "index.html", html.as_bytes(), &mut total)?;
        }
        Ok(())
    })();
    if let Err(e) = written {
        let _ = std::fs::remove_dir_all(&stage);
        let _ = std::fs::remove_file(&stage);
        return Err(e);
    }

    if single && total > cap {
        plan.warn(
            BundleWarningKind::SizeCap,
            format!(
                "the single-file bundle is {total} bytes, over the {cap} byte cap; it was written anyway"
            ),
        );
    }

    let moved = (|| -> Result<(), String> {
        match std::fs::symlink_metadata(&out) {
            Ok(m) if m.is_dir() => {
                std::fs::remove_dir_all(&out)
                    .map_err(|e| format!("cannot replace {}: {e}", out.display()))?;
            }
            Ok(_) => {
                std::fs::remove_file(&out)
                    .map_err(|e| format!("cannot replace {}: {e}", out.display()))?;
            }
            Err(_) => {}
        }
        std::fs::rename(&stage, &out)
            .map_err(|e| format!("cannot place the bundle at {}: {e}", out.display()))
    })();
    if let Err(e) = moved {
        let _ = std::fs::remove_dir_all(&stage);
        let _ = std::fs::remove_file(&stage);
        return Err(e);
    }

    Ok(BundleExported {
        path: out.to_string_lossy().to_string(),
        profile,
        bytes: total,
        widgets: planned.len() as u32,
        assets: plan.assets.len() as u32,
        warnings: plan.warnings,
    })
}

/// The bus event for one export call, shared by the adapters that log it.
pub fn event(
    main_rel: &str,
    profile: BundleProfile,
    r: &Result<BundleExported, String>,
    actor: maleficium_events::Actor,
) -> maleficium_events::BusEvent {
    use maleficium_events::{AppEvent, BusEvent, EventKind, EventScope};
    let (kind, message, event) = match r {
        Ok(b) => (
            if b.warnings.is_empty() {
                EventKind::Success
            } else {
                EventKind::Warn
            },
            format!(
                "exported a {} bundle of {main_rel} to {}",
                profile_name(profile),
                b.path
            ),
            AppEvent::BundleExported {
                main: main_rel.to_string(),
                profile,
                path: b.path.clone(),
                bytes: b.bytes,
                widgets: b.widgets,
                warnings: b.warnings.len() as u32,
            },
        ),
        Err(e) => (
            EventKind::Error,
            format!("bundle export of {main_rel} refused"),
            AppEvent::BundleFailed {
                main: main_rel.to_string(),
                profile,
                error: e.chars().take(300).collect(),
            },
        ),
    };
    BusEvent {
        at: crate::eventlog::now_ms(),
        scope: EventScope::App,
        kind,
        actor,
        message,
        event,
    }
}

fn profile_name(p: BundleProfile) -> &'static str {
    match p {
        BundleProfile::Folder => "folder",
        BundleProfile::SingleFile => "single-file",
        BundleProfile::Hosted => "hosted",
    }
}

