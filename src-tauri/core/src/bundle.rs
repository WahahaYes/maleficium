#[derive(Clone, Copy, PartialEq, Eq)]
enum Mode {
    Bundled,
    Inline,
    Remote,
}

impl Mode {
    fn name(self) -> &'static str {
        match self {
            Mode::Bundled => "bundled",
            Mode::Inline => "inline",
            Mode::Remote => "remote",
        }
    }
}

/// Where an asset's bytes come from at write time.
enum Bytes {
    File(PathBuf),
    Mem(Vec<u8>),
    /// A remote asset: nothing is stored.
    None,
}

struct Asset {
    mode: Mode,
    sha: String,
    bytes: u64,
    mime: String,
    ext: String,
    source: Option<String>,
    url: Option<String>,
    data: Bytes,
}

impl Asset {
    fn path(&self) -> String {
        format!("assets/{}.{}", self.sha, self.ext)
    }

    fn record(&self) -> Value {
        let mut o = Map::new();
        o.insert("mode".into(), self.mode.name().into());
        match self.mode {
            Mode::Bundled => {
                o.insert("path".into(), self.path().into());
            }
            Mode::Inline => {
                o.insert("path".into(), Value::Null);
            }
            Mode::Remote => {
                o.insert("url".into(), self.url.clone().into());
            }
        }
        o.insert("sha256".into(), self.sha.clone().into());
        o.insert("bytes".into(), self.bytes.into());
        o.insert("mime".into(), self.mime.clone().into());
        if let Some(s) = &self.source {
            o.insert("source".into(), s.clone().into());
        }
        Value::Object(o)
    }
}

