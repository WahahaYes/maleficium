//! Paper bundle export: a compiled main file, its widgets and its assets
//! written as the layout of `notes/interactive-papers/2026-09-25-bundle-spec.md`
//! to a destination outside the project root.
//!
//! The export reads project files and the compiled output; it never fetches.
//! A remote asset with no local copy would need a download to be hashed, and
//! that download is refused unless the user approved that exact url for this
//! export. The approval is an argument of [`export_bundle_with`] that only
//! the app's own user action can set; the automation surface calls
//! [`export_bundle`], which takes none.
//!
//! Everything is read, hashed and checked before anything is written, and the
//! bundle is assembled in a sibling staging folder and moved into place, so a
//! refusal or a failure leaves no half-written destination.
//!
//! Widgets are folded into one inline document each in every profile (the
//! 2026-09-30 browser export spike): see [`fold`].
//!
//! A custom runtime widget exports live only when its project copy
//! (`runtimes/<ref>/`) is valid, binds, and is approved; otherwise it
//! exports as its poster with a note, and the export says why. The export
//! never asks: it judges and falls back. The browser preview runs custom
//! runtimes without the approval gate, as it does html widgets.

