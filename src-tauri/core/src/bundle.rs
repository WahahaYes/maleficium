fn export_inner(
    cx: &Core,
    root_id: &str,
    main_rel: &str,
    dest: &str,
    profile: BundleProfile,
    opts: &BundleOptions,
    gate: Gate,
) -> Result<BundleExported, String> {
    let root = crate::fs::session_root(cx, root_id)?;
    let out = check_destination(&root, dest, profile)?;

    // The typed widget list is the join of sidecar and pdf; it also fails when
    // the main file was never compiled.
    let (list, theme) = crate::widgets::read(cx, root_id, main_rel)?;
    // The page's CSS and the widgets' tokens come from this one theme;
    // its values are checked again as the CSS is written.
    let mut theme_css = theme.css()?;
    let o = crate::outputs::outputs_of(cx, root_id, main_rel)?;
    let pdf_bytes = std::fs::read(o.outdir.join(&o.pdf_name))
        .map_err(|_| format!("{main_rel} has no compiled pdf: compile it first"))?;
    let pdf = hayro::hayro_syntax::Pdf::new(pdf_bytes.clone())
        .map_err(|e| format!("cannot read the pdf of {main_rel}: {e:?}"))?;
    let pages = pdf.pages().len() as u32;
    if pages == 0 || pdf_bytes.is_empty() {
        return Err(format!("the pdf of {main_rel} has no pages"));
    }

    let mut theme_ids: BTreeSet<&str> = list.widgets.iter().map(|w| w.theme.as_str()).collect();
    if theme_ids.is_empty() {
        theme_ids.insert("house");
    }
    if theme_ids.len() > 1 {
        return Err(format!(
            "the widgets name more than one theme ({}): the paper has one",
            theme_ids.iter().copied().collect::<Vec<_>>().join(", ")
        ));
    }
    let theme_id = theme_ids.into_iter().next().unwrap_or("house").to_string();
    if theme_id != "house" {
        return Err(format!(
            "theme `{theme_id}` is not available: only the built-in house theme is in this build"
        ));
    }

    let mut plan = Plan {
        cx,
        root_id,
        main_rel,
        root: root.clone(),
        main_dir_rel: Path::new(main_rel)
            .parent()
            .map(Path::to_path_buf)
            .unwrap_or_default(),
        profile,
        opts,
        theme: &theme,
        assets: BTreeMap::new(),
        warnings: Vec::new(),
        gate,
        users: BTreeMap::new(),
        runtimes: BTreeMap::new(),
        runtime_entries: Map::new(),
        fallbacks: BTreeMap::new(),
        wasm_live: false,
        notes: BTreeMap::new(),
        gated: BTreeSet::new(),
    };
    for w in list.widgets.iter().filter(|w| w.kind == WidgetType::Custom) {
        if let Some(r) = &w.runtime {
            plan.users.entry(r.clone()).or_default().push(w.id.clone());
        }
    }
    // The author's reader stylesheet follows the theme's tokens, so it can
    // restyle with them; refused, the page keeps the theme alone.
    if let Some(style) = &theme.style {
        match crate::reader_style::load(cx, root_id, &plan.main_dir_rel, style) {
            Ok(css) => {
                theme_css.push('\n');
                theme_css.push_str(&css);
            }
            Err(e) => plan.warn(BundleWarningKind::ReaderStyle, e),
        }
    }

    let stem = o
        .main_file
        .strip_suffix(".tex")
        .unwrap_or(&o.main_file)
        .to_string();
    let tex = std::fs::read_to_string(root.join(&plan.main_dir_rel).join(&o.main_file))
        .map_err(|e| format!("cannot read {main_rel}: {e}"))?;
    let meta = paper_meta(&tex, &stem, &mut plan.warnings);

    let mut planned = Vec::new();
    for w in &list.widgets {
        planned.push(plan_widget(&mut plan, w, &pdf, pages)?);
    }
    for (r, (why, ids)) in std::mem::take(&mut plan.fallbacks) {
        plan.warn(BundleWarningKind::Runtime, why.warning(&r, &ids.join(", ")));
    }
    let single = profile == BundleProfile::SingleFile;

    // The article: the main file converted to HTML, then the reader pipeline
    // (figures, widget mounts, contents, sanitizing). Its problems are
    // reported; only a conversion that produced no HTML at all refuses.
    let scratch = Scratch::new(&o.outdir)?;
    let main_canon = crate::fs::resolve_in(cx, root_id, main_rel)?;
    let main_dir = main_canon
        .parent()
        .map(Path::to_path_buf)
        .ok_or_else(|| format!("{main_rel} has no folder"))?;
    let conversion =
        reflow::convert::converter(cx).convert(cx, &main_canon, &scratch.0.join("convert"));
    let converted = conversion.html.map_err(|e| {
        format!("{main_rel} could not be converted to HTML, so the bundle has no article: {e}")
    })?;
    // Reader flags: the marker classes the `\maleficiumcontents` and
    // `\maleficiummeasure` calls left in the conversion, resolved where the
    // widgets are joined and stripped from the article.
    let flag_scan = flags::scan(&converted);
    for w in &flag_scan.warnings {
        plan.warn(BundleWarningKind::Conversion, w.clone());
    }
    let converted = flag_scan.html;
    let sidecar = std::fs::read_to_string(o.outdir.join(format!("{stem}.mfw"))).ok();
    let mount_units = mounts(&list.widgets, &plan.assets, &plan.notes, &plan.gated)?;
    let article = reflow::article::build(reflow::article::Input {
        html: &converted,
        root: &main_dir,
        mode: if single {
            reflow::figures::Mode::SingleFile
        } else {
            reflow::figures::Mode::Folder {
                dir: scratch.0.clone(),
            }
        },
        graphics_paths: graphics_paths(&tex),
        sidecar: sidecar.as_deref(),
        mounts: &mount_units,
        title: &meta.title,
    })?;
    plan.warnings.extend(article_warnings(
        &conversion.log,
        &conversion.errors,
        &article.issues,
    ));
    // `contents: false` omits the nav (not-emit), rather than hiding it.
    let article_html = if flag_scan.flags.contents {
        article.html
    } else {
        flags::omit_contents(&article.html)
    };

    let mut paper = Map::new();
    paper.insert("title".into(), meta.title.clone().into());
    paper.insert(
        "authors".into(),
        Value::Array(
            meta.authors
                .iter()
                .map(|(n, aff)| {
                    let mut a = Map::new();
                    a.insert("name".into(), n.clone().into());
                    if !aff.is_empty() {
                        a.insert("affiliations".into(), json!(aff));
                    }
                    Value::Object(a)
                })
                .collect(),
        ),
    );
    if let Some(a) = &meta.abstract_text {
        paper.insert("abstract".into(), a.clone().into());
    }
    paper.insert(
        "reader".into(),
        json!({
            "contents": flag_scan.flags.contents,
            "measure": flag_scan.flags.measure.token(),
        }),
    );
    let cap = opts.size_cap_bytes.unwrap_or(DEFAULT_SIZE_CAP_BYTES);
    let mut manifest = Map::new();
    manifest.insert("format".into(), FORMAT.into());
    manifest.insert("formatVersion".into(), 1.into());
    manifest.insert(
        "generator".into(),
        json!({ "name": "maleficium", "version": env!("CARGO_PKG_VERSION") }),
    );
    manifest.insert(
        "profile".into(),
        serde_json::to_value(profile).map_err(|e| e.to_string())?,
    );
    if single {
        manifest.insert("sizeCapBytes".into(), cap.into());
    }
    manifest.insert("paper".into(), Value::Object(paper));
    manifest.insert(
        "pdf".into(),
        json!({
            "path": if single { Value::Null } else { "paper.pdf".into() },
            "sha256": sha_of(&pdf_bytes),
            "bytes": pdf_bytes.len(),
            "pages": pages
        }),
    );
    manifest.insert(
        "theme".into(),
        json!({ "id": theme_id, "contractVersion": CONTRACT_VERSION }),
    );
    manifest.insert(
        "widgets".into(),
        Value::Array(planned.iter().map(|p| p.json.clone()).collect()),
    );
    if !plan.runtime_entries.is_empty() {
        manifest.insert(
            "runtimes".into(),
            Value::Object(std::mem::take(&mut plan.runtime_entries)),
        );
    }
    manifest.insert(
        "assets".into(),
        Value::Object(
            plan.assets
                .iter()
                .map(|(k, a)| (k.clone(), a.record()))
                .collect(),
        ),
    );
    let manifest = Value::Object(manifest);
    validate_manifest(&manifest)?;

    // Writing starts only now: every read, hash and check above has passed.
    let stage = staging_name(&out);
    let _ = std::fs::remove_dir_all(&stage);
    let _ = std::fs::remove_file(&stage);
    let mut total = 0u64;
    let manifest_text = serde_json::to_string_pretty(&manifest).map_err(|e| e.to_string())? + "\n";

    // Every frame origin some widget declared: the reader's own frame-src.
    let frames: Vec<String> = planned
        .iter()
        .flat_map(|p| p.frames.iter().cloned())
        .collect::<BTreeSet<_>>()
        .into_iter()
        .collect();
    let written = (|| -> Result<(), String> {
        if single {
            let mut assets = Map::new();
            for a in plan.assets.values().filter(|a| a.mode == Mode::Inline) {
                if assets.contains_key(&a.sha) {
                    continue;
                }
                let bytes = match &a.data {
                    Bytes::File(p) => read_verified(p, &a.sha)?,
                    Bytes::Mem(b) => b.clone(),
                    Bytes::None => continue,
                };
                assets.insert(
                    a.sha.clone(),
                    base64::engine::general_purpose::STANDARD
                        .encode(bytes)
                        .into(),
                );
            }
            let widgets: Map<String, Value> = planned
                .iter()
                .filter_map(|p| p.doc.clone().map(|d| (p.id.clone(), d.into())))
                .collect();
            let islands = [
                island("mfw-manifest", &manifest),
                island("mfw-widgets", &Value::Object(widgets)),
                island("mfw-assets", &Value::Object(assets)),
            ]
            .concat();
            let html = reader::render(&reader::Reader {
                title: &meta.title,
                folder: false,
                article: &article_html,
                measure: flag_scan.flags.measure,
                pdf: Some(&pdf_bytes),
                islands: &islands,
                frames: &frames,
                wasm: plan.wasm_live,
                theme: &theme,
                theme_css: &theme_css,
            });
            std::fs::write(&stage, html.as_bytes())
                .map_err(|e| format!("cannot write {}: {e}", stage.display()))?;
            total = html.len() as u64;
        } else {
            std::fs::create_dir_all(&stage)
                .map_err(|e| format!("cannot create {}: {e}", stage.display()))?;
            put(
                &stage,
                "manifest.json",
                manifest_text.as_bytes(),
                &mut total,
            )?;
            put(&stage, "paper.pdf", &pdf_bytes, &mut total)?;
            put(
                &stage,
                "theme/theme.json",
                theme_json(&theme_id).as_bytes(),
                &mut total,
            )?;
            put(&stage, "theme/theme.css", theme_css.as_bytes(), &mut total)?;
            for p in &planned {
                if let Some(doc) = &p.doc {
                    put(
                        &stage,
                        &format!("widgets/{}/index.html", p.id),
                        doc.as_bytes(),
                        &mut total,
                    )?;
                }
            }
            let mut inline = Map::new();
            let mut stored = BTreeSet::new();
            for a in plan.assets.values() {
                let bytes = match (&a.data, a.mode) {
                    (_, Mode::Remote) | (Bytes::None, _) => continue,
                    (Bytes::File(p), _) => read_verified(p, &a.sha)?,
                    (Bytes::Mem(b), _) => b.clone(),
                };
                if a.mode == Mode::Inline {
                    inline.insert(
                        a.sha.clone(),
                        base64::engine::general_purpose::STANDARD
                            .encode(&bytes)
                            .into(),
                    );
                } else if stored.insert(a.path()) {
                    put(&stage, &a.path(), &bytes, &mut total)?;
                }
            }
            let islands = [
                island("mfw-manifest", &manifest),
                if inline.is_empty() {
                    String::new()
                } else {
                    island("mfw-assets", &Value::Object(inline))
                },
            ]
            .concat();
            // The figures the article references, written by the pipeline
            // into the scratch folder (content-addressed names).
            let figures = scratch.0.join("figures");
            if figures.is_dir() {
                let entries = std::fs::read_dir(&figures)
                    .map_err(|e| format!("cannot list {}: {e}", figures.display()))?;
                for e in entries.flatten() {
                    let name = e.file_name().to_string_lossy().to_string();
                    if name.ends_with(".part") {
                        continue;
                    }
                    let bytes = std::fs::read(e.path())
                        .map_err(|err| format!("cannot read {}: {err}", e.path().display()))?;
                    put(&stage, &format!("figures/{name}"), &bytes, &mut total)?;
                }
            }
            let html = reader::render(&reader::Reader {
                title: &meta.title,
                folder: true,
                article: &article_html,
                measure: flag_scan.flags.measure,
                pdf: None,
                islands: &islands,
                frames: &frames,
                wasm: plan.wasm_live,
                theme: &theme,
                theme_css: &theme_css,
            });
            put(&stage, "index.html", html.as_bytes(), &mut total)?;
        }
        Ok(())
    })();
    if let Err(e) = written {
        let _ = std::fs::remove_dir_all(&stage);
        let _ = std::fs::remove_file(&stage);
        return Err(e);
    }

    if single && total > cap {
        plan.warn(
            BundleWarningKind::SizeCap,
            format!(
                "the single-file bundle is {total} bytes, over the {cap} byte cap; it was written anyway"
            ),
        );
    }

    let moved = (|| -> Result<(), String> {
        match std::fs::symlink_metadata(&out) {
            Ok(m) if m.is_dir() => {
                std::fs::remove_dir_all(&out)
                    .map_err(|e| format!("cannot replace {}: {e}", out.display()))?;
            }
            Ok(_) => {
                std::fs::remove_file(&out)
                    .map_err(|e| format!("cannot replace {}: {e}", out.display()))?;
            }
            Err(_) => {}
        }
        std::fs::rename(&stage, &out)
            .map_err(|e| format!("cannot place the bundle at {}: {e}", out.display()))
    })();
    if let Err(e) = moved {
        let _ = std::fs::remove_dir_all(&stage);
        let _ = std::fs::remove_file(&stage);
        return Err(e);
    }

    Ok(BundleExported {
        path: out.to_string_lossy().to_string(),
        profile,
        bytes: total,
        widgets: planned.len() as u32,
        assets: plan.assets.len() as u32,
        warnings: plan.warnings,
    })
}

/// The bus event for one export call, shared by the adapters that log it.
pub fn event(
    main_rel: &str,
    profile: BundleProfile,
    r: &Result<BundleExported, String>,
    actor: maleficium_events::Actor,
) -> maleficium_events::BusEvent {
    use maleficium_events::{AppEvent, BusEvent, EventKind, EventScope};
    let (kind, message, event) = match r {
        Ok(b) => (
            if b.warnings.is_empty() {
                EventKind::Success
            } else {
                EventKind::Warn
            },
            format!(
                "exported a {} bundle of {main_rel} to {}",
                profile_name(profile),
                b.path
            ),
            AppEvent::BundleExported {
                main: main_rel.to_string(),
                profile,
                path: b.path.clone(),
                bytes: b.bytes,
                widgets: b.widgets,
                warnings: b.warnings.len() as u32,
            },
        ),
        Err(e) => (
            EventKind::Error,
            format!("bundle export of {main_rel} refused"),
            AppEvent::BundleFailed {
                main: main_rel.to_string(),
                profile,
                error: e.chars().take(300).collect(),
            },
        ),
    };
    BusEvent {
        at: crate::eventlog::now_ms(),
        scope: EventScope::App,
        kind,
        actor,
        message,
        event,
    }
}

fn profile_name(p: BundleProfile) -> &'static str {
    match p {
        BundleProfile::Folder => "folder",
        BundleProfile::SingleFile => "single-file",
        BundleProfile::Hosted => "hosted",
    }
}

