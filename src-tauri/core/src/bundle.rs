/// The text of the brace group that starts at `s[i]` (a `{`), and the index
/// after its closing brace.
fn brace_group(s: &str, i: usize) -> Option<(String, usize)> {
    let b = s.as_bytes();
    if b.get(i) != Some(&b'{') {
        return None;
    }
    let mut depth = 0usize;
    let mut j = i;
    while j < b.len() {
        match b[j] {
            b'\\' => j += 1,
            b'{' => depth += 1,
            b'}' => {
                depth -= 1;
                if depth == 0 {
                    return Some((s[i + 1..j].to_string(), j + 1));
                }
            }
            _ => {}
        }
        j += 1;
    }
    None
}

fn strip_comments(tex: &str) -> String {
    tex.lines()
        .map(|l| {
            let b = l.as_bytes();
            let mut i = 0;
            while i < b.len() {
                if b[i] == b'\\' {
                    i += 2;
                    continue;
                }
                if b[i] == b'%' {
                    return &l[..i];
                }
                i += 1;
            }
            l
        })
        .collect::<Vec<_>>()
        .join("\n")
}

/// The first `\name{...}` (with an optional `[..]`) in `tex`.
fn command_arg(tex: &str, name: &str) -> Option<String> {
    let needle = format!("\\{name}");
    let mut from = 0;
    while let Some(p) = tex[from..].find(&needle) {
        let mut i = from + p + needle.len();
        from = i;
        let next = tex[i..].chars().next();
        if next.is_some_and(|c| c.is_ascii_alphabetic()) {
            continue;
        }
        let rest = tex[i..].trim_start();
        i = tex.len() - rest.len();
        let mut j = i;
        if tex[j..].starts_with('[') {
            match tex[j..].find(']') {
                Some(e) => j += e + 1,
                None => continue,
            }
            j = tex.len() - tex[j..].trim_start().len();
        }
        if let Some((g, _)) = brace_group(tex, j) {
            return Some(g);
        }
    }
    None
}

/// Plain text of a small LaTeX fragment: footnote-like groups dropped, `\\`
/// and `~` as spaces, other commands reduced to their argument.
fn plain(s: &str) -> String {
    let mut s = s.to_string();
    for drop in ["thanks", "footnote", "label"] {
        let needle = format!("\\{drop}");
        while let Some(p) = s.find(&needle) {
            let rest = &s[p + needle.len()..];
            let off = rest.len() - rest.trim_start().len();
            match brace_group(&s, p + needle.len() + off) {
                Some((_, end)) => s.replace_range(p..end, ""),
                None => s.replace_range(p..p + needle.len(), ""),
            }
        }
    }
    let s = s.replace("\\\\", " ").replace("\\&", "&").replace('~', " ");
    let cmd = regex::Regex::new(r"\\[A-Za-z]+\*?").unwrap();
    let s = cmd.replace_all(&s, "");
    let s: String = s.chars().filter(|c| *c != '{' && *c != '}').collect();
    s.split_whitespace().collect::<Vec<_>>().join(" ")
}

struct Meta {
    title: String,
    authors: Vec<(String, Vec<String>)>,
    abstract_text: Option<String>,
}

/// Title, authors and abstract of the main file, as far as its own preamble
/// and body say. Anything unreadable gets a named default and a warning.
fn paper_meta(tex: &str, stem: &str, warnings: &mut Vec<BundleWarning>) -> Meta {
    let tex = strip_comments(tex);
    let mut warn = |m: String| {
        warnings.push(BundleWarning {
            kind: BundleWarningKind::Metadata,
            message: m,
        })
    };
    let title = command_arg(&tex, "title")
        .map(|t| plain(&t))
        .filter(|t| !t.is_empty());
    let title = title.unwrap_or_else(|| {
        warn(format!(
            "the main file has no \\title: the manifest title is the file name `{stem}`"
        ));
        stem.to_string()
    });
    let mut authors: Vec<(String, Vec<String>)> = Vec::new();
    if let Some(a) = command_arg(&tex, "author") {
        let split = regex::Regex::new(r"\\(?:and|And|AND)\b").unwrap();
        for part in split.split(&a) {
            let lines: Vec<String> = part
                .split("\\\\")
                .map(plain)
                .filter(|l| !l.is_empty())
                .collect();
            if let Some((name, aff)) = lines.split_first() {
                authors.push((name.clone(), aff.to_vec()));
            }
        }
    }
    if authors.is_empty() {
        warn(
            "the main file has no \\author: the manifest lists one author with an empty name"
                .to_string(),
        );
        authors.push((String::new(), Vec::new()));
    }
    let abstract_text = tex
        .find("\\begin{abstract}")
        .and_then(|s| {
            let body = &tex[s + "\\begin{abstract}".len()..];
            body.find("\\end{abstract}").map(|e| plain(&body[..e]))
        })
        .filter(|a| !a.is_empty());
    Meta {
        title,
        authors,
        abstract_text,
    }
}

/// The directories of the main file's `\graphicspath{{a/}{b/}}`, in order.
fn graphics_paths(tex: &str) -> Vec<String> {
    let tex = strip_comments(tex);
    let Some(arg) = command_arg(&tex, "graphicspath") else {
        return Vec::new();
    };
    let mut out = Vec::new();
    let mut i = 0;
    while let Some(off) = arg[i..].find('{') {
        match brace_group(&arg, i + off) {
            Some((dir, end)) => {
                out.push(dir.trim().to_string());
                i = end;
            }
            None => break,
        }
    }
    out
}

