/// Serializes JSON for a `<script type="application/json">` island: `<` is
/// escaped so no string can close the element.
fn island(id: &str, v: &Value) -> String {
    let s = serde_json::to_string(v)
        .unwrap_or_default()
        .replace('<', "\\u003c");
    format!("<script type=\"application/json\" id=\"{id}\">{s}</script>")
}

/// Each widget's mount unit: caption fields from the widget list, and the
/// poster as a bundled path or an inline `data:` url.
fn mounts<'a>(
    list: &'a [Widget],
    assets: &BTreeMap<String, Asset>,
    notes: &BTreeMap<String, String>,
    gated: &BTreeSet<String>,
) -> Result<Vec<reflow::article::Mount<'a>>, String> {
    list.iter()
        .map(|w| {
            let key = format!("{}-poster", w.id);
            let a = assets
                .get(&key)
                .ok_or_else(|| format!("widget {}: it has no poster asset", w.id))?;
            let poster = match (a.mode, &a.data) {
                (Mode::Bundled, _) => a.path(),
                (_, Bytes::File(p)) => data_url(&a.mime, &read_verified(p, &a.sha)?),
                (_, Bytes::Mem(b)) => data_url(&a.mime, b),
                _ => return Err(format!("widget {}: its poster has no bytes", w.id)),
            };
            let kind = match w.kind {
                WidgetType::Model => "model",
                WidgetType::Video => "video",
                WidgetType::Table => "table",
                WidgetType::Chart => "chart",
                WidgetType::Html => "html",
                WidgetType::Custom => "custom",
            };
            let size = (w.kind == WidgetType::Model)
                .then(|| {
                    w.options
                        .iter()
                        .find(|o| o.key == "size")
                        .map(|o| crate::widgets::params::size(&o.value))
                })
                .flatten()
                .transpose()
                .map_err(|e| format!("widget {}: {e}", w.id))?;
            let rect = (w.rect.x1 - w.rect.x0, w.rect.y1 - w.rect.y0);
            let author = (
                author_pt(&w.options, "width"),
                author_pt(&w.options, "height"),
            );
            let (frame, author_box) = reflow::article::frame(kind, size, author, rect);
            Ok(reflow::article::Mount {
                id: &w.id,
                kind,
                figure: w.figure.as_deref(),
                label: w.label.as_deref(),
                alt: &w.alt,
                width: frame.0,
                height: frame.1,
                author_width: author_box.map(|b| b.0),
                author_height: author_box.map(|b| b.1),
                poster,
                note: notes.get(&w.id).cloned(),
                approval_required: gated.contains(&w.id),
            })
        })
        .collect()
}

/// An author's `width=`/`height=` sidecar value in points: the package
/// canonicalizes dims through a length, so a well-formed one ends in `pt`.
/// Anything else is no dims, never a failure.
fn author_pt(options: &[crate::widgets::WidgetOption], key: &str) -> Option<f64> {
    options
        .iter()
        .find(|o| o.key == key)
        .and_then(|o| o.value.strip_suffix("pt"))
        .and_then(|n| n.parse::<f64>().ok())
        .filter(|v| v.is_finite() && *v > 0.0)
}

/// An app-owned scratch folder for one export's conversion and figures,
/// removed when the export ends either way.
struct Scratch(PathBuf);

impl Scratch {
    fn new(outdir: &Path) -> Result<Scratch, String> {
        static NEXT: std::sync::atomic::AtomicU64 = std::sync::atomic::AtomicU64::new(0);
        let n = NEXT.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
        let dir = outdir.join(format!("reader-export-{}-{n}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(dir.join("convert"))
            .map_err(|e| format!("cannot create {}: {e}", dir.display()))?;
        Ok(Scratch(dir))
    }
}

impl Drop for Scratch {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.0);
    }
}

/// At most this many log errors are quoted in the report.
const QUOTED_ERRORS: usize = 5;

/// Packages that only work with shell escape: the converter never enables
/// it, so a conversion that names one reports it as such. Mirrors the
/// compile's list (`structure/src/checks.rs` `SHELL_ESCAPE_PACKAGES`).
const SHELL_ESCAPE_PACKAGES: &[&str] = &[
    "minted",
    "pythontex",
    "svg",
    "gnuplottex",
    "auto-pst-pdf",
    "bashful",
    "shellesc",
];

/// Whether a missing bundle file is one of those shell-escape packages.
fn shell_escape_package(file: &str) -> Option<&str> {
    let base = file.rsplit('/').next().unwrap_or(file);
    let stem = base
        .strip_suffix(".sty")
        .or_else(|| base.strip_suffix(".cls"))?;
    SHELL_ESCAPE_PACKAGES.iter().find(|p| **p == stem).copied()
}

/// The report lines for what the article pipeline found.
fn article_warnings(
    log: &str,
    log_errors: &[String],
    issues: &[reflow::article::Issue],
) -> Vec<BundleWarning> {
    use reflow::article::Issue;
    let mut out = Vec::new();
    // The generic quote skips undefined-macro detail lines: each macro gets
    // its own warning below.
    let quoted: Vec<&String> = log_errors
        .iter()
        .filter(|l| !l.starts_with("Error:undefined:"))
        .collect();
    if !quoted.is_empty() {
        let shown = quoted
            .iter()
            .take(QUOTED_ERRORS)
            .map(|l| l.as_str())
            .collect::<Vec<_>>()
            .join("; ");
        let more = quoted.len().saturating_sub(QUOTED_ERRORS);
        out.push(BundleWarning {
            kind: BundleWarningKind::Conversion,
            message: format!(
                "the conversion to HTML reported {} error{}; the article was still produced: {shown}{}",
                quoted.len(),
                if quoted.len() == 1 { "" } else { "s" },
                if more > 0 { format!(" and {more} more") } else { String::new() }
            ),
        });
    }
    // One warning per undefined macro: the article's spots first, then any
    // macro the log named that left no mark in the article.
    let mut groups: BTreeMap<String, usize> = BTreeMap::new();
    for i in issues {
        if let Issue::Undefined(found) = i {
            for u in found {
                groups.insert(u.name.clone(), u.spots);
            }
        }
    }
    for u in reflow::convert::undefined_from_log(log) {
        groups.entry(u.name).or_insert(u.spots);
    }
    let mut groups: Vec<(String, usize)> = groups.into_iter().collect();
    groups.sort_by(|a, b| b.1.cmp(&a.1).then(a.0.cmp(&b.0)));
    for (name, spots) in groups {
        let where_ = if spots > 0 {
            format!(
                "{} spot{} in the article show{} raw TeX",
                spots,
                if spots == 1 { "" } else { "s" },
                if spots == 1 { "s" } else { "" }
            )
        } else {
            String::from("the converter reported it, but it left no mark in the article")
        };
        out.push(BundleWarning {
            kind: BundleWarningKind::Conversion,
            message: format!(
                "{name} is not defined ({where_}); the package is not in the TeX bundle: add it to your project folder next to your main file."
            ),
        });
    }
    // Files the log says the bundle lacks: shell-escape packages report as
    // such, the rest (too new for the pinned bundle, or never in TeX Live)
    // get the project-folder hint.
    let mut shell_reported: Vec<String> = Vec::new();
    for file in reflow::convert::missing_from_log(log) {
        if let Some(pkg) = shell_escape_package(&file) {
            if !shell_reported.contains(&pkg.to_string()) {
                shell_reported.push(pkg.to_string());
            }
        } else {
            out.push(BundleWarning {
                kind: BundleWarningKind::Conversion,
                message: super::compile::missing_package_text(&file),
            });
        }
    }
    for line in log.lines() {
        let lower = line.to_ascii_lowercase();
        if lower.contains("shell-escape")
            || lower.contains("shell escape")
            || lower.contains("write18")
        {
            // The compile's shape names the package (`Package minted
            // Error: ...`); otherwise any shell-escape package word on the
            // line does.
            let pkg = line
                .find("Package ")
                .and_then(|at| {
                    line[at + "Package ".len()..]
                        .split_whitespace()
                        .next()
                        .map(|w| w.trim_matches(|c: char| !c.is_alphanumeric() && c != '-'))
                })
                .filter(|w| !w.is_empty())
                .map(str::to_string)
                .or_else(|| {
                    line.split(|c: char| !c.is_alphanumeric() && c != '-' && c != '_')
                        .map(|w| w.trim_matches('-'))
                        .find(|w| SHELL_ESCAPE_PACKAGES.contains(w))
                        .map(str::to_string)
                });
            match pkg {
                Some(p) if !shell_reported.contains(&p) => shell_reported.push(p),
                None if !shell_reported.iter().any(|p| p.is_empty()) => {
                    shell_reported.push(String::new());
                }
                _ => {}
            }
        }
    }
    for pkg in shell_reported {
        out.push(BundleWarning {
            kind: BundleWarningKind::Conversion,
            message: if pkg.is_empty() {
                String::from(
                    "the conversion needs shell escape, which the converter never enables; the article was still produced.",
                )
            } else {
                format!(
                    "{pkg} needs shell escape, which the converter never enables; the article was still produced."
                )
            },
        });
    }
    for i in issues {
        out.push(match i {
            Issue::Undefined(_) => continue,
            Issue::Join(e) => BundleWarning {
                kind: BundleWarningKind::WidgetJoin,
                message: format!("the widgets could not be placed in the article ({e}); they are listed at its end"),
            },
            Issue::Figure(w) => BundleWarning {
                kind: BundleWarningKind::Figure,
                message: if w.file.is_empty() {
                    format!("a figure is not shown: {}", w.reason.describe())
                } else {
                    format!("figure {} is not shown: {}", w.file, w.reason.describe())
                },
            },
        });
    }
    out
}

fn data_url(mime: &str, bytes: &[u8]) -> String {
    format!(
        "data:{mime};base64,{}",
        base64::engine::general_purpose::STANDARD.encode(bytes)
    )
}

fn read_verified(path: &Path, sha: &str) -> Result<Vec<u8>, String> {
    let b = std::fs::read(path).map_err(|e| format!("cannot read {}: {e}", path.display()))?;
    if sha_of(&b) != sha {
        return Err(format!(
            "{} changed while it was being exported: run the export again",
            path.display()
        ));
    }
    Ok(b)
}

fn put(root: &Path, rel: &str, bytes: &[u8], total: &mut u64) -> Result<(), String> {
    let p = root.join(rel);
    if let Some(parent) = p.parent() {
        std::fs::create_dir_all(parent)
            .map_err(|e| format!("cannot create {}: {e}", parent.display()))?;
    }
    std::fs::File::create(&p)
        .and_then(|mut f| f.write_all(bytes))
        .map_err(|e| format!("cannot write {}: {e}", p.display()))?;
    *total += bytes.len() as u64;
    Ok(())
}

/// Whether `dir` holds an earlier bundle of ours (its manifest names the
/// format): the only non-empty folder an export replaces.
fn is_earlier_bundle(dir: &Path) -> bool {
    std::fs::read_to_string(dir.join("manifest.json"))
        .ok()
        .and_then(|t| serde_json::from_str::<Value>(&t).ok())
        .is_some_and(|v| v["format"] == FORMAT)
}

/// What an export may do at `dest` before anything is written.
fn check_destination(root: &Path, dest: &str, profile: BundleProfile) -> Result<PathBuf, String> {
    let out = crate::export::destination(root, dest)?;
    if root.starts_with(&out) {
        return Err(
            "export destination contains the project: choose a folder outside it".to_string(),
        );
    }
    match std::fs::symlink_metadata(&out) {
        Err(_) => {}
        Ok(m) if m.file_type().is_symlink() => {
            return Err(format!(
                "export destination is a symlink: {}",
                out.display()
            ));
        }
        Ok(m) => match profile {
            BundleProfile::SingleFile => {
                if m.is_dir() {
                    return Err(format!("export destination is a folder: {}", out.display()));
                }
            }
            _ => {
                if !m.is_dir() {
                    return Err(format!("export destination is a file: {}", out.display()));
                }
                let empty = std::fs::read_dir(&out)
                    .map_err(|e| format!("cannot list {}: {e}", out.display()))?
                    .next()
                    .is_none();
                if !empty && !is_earlier_bundle(&out) {
                    return Err(format!(
                        "export destination is not empty and is not an earlier bundle: {}",
                        out.display()
                    ));
                }
            }
        },
    }
    Ok(out)
}

fn staging_name(out: &Path) -> PathBuf {
    let name = out
        .file_name()
        .map(|n| n.to_string_lossy().to_string())
        .unwrap_or_default();
    out.with_file_name(format!(".{name}.mfw-partial-{}", std::process::id()))
}

