/// Whether an export judges custom runtimes against the approval store at
/// this base, runs them unjudged (the browser preview, as html widgets), or
/// renders the in-app article (judged runtimes, plus html widgets held back
/// for approval).
#[derive(Clone, Copy)]
enum Gate<'a> {
    Approvals(&'a Path),
    Preview,
    Article(&'a Path),
}

/// Why a custom widget exports as its poster.
#[derive(Debug, Clone, PartialEq, Eq)]
enum Fallback {
    Missing,
    Invalid(String),
    Unapproved,
    Denied,
}

impl Fallback {
    /// The manifest's `fallback` value.
    fn name(&self) -> &'static str {
        match self {
            Fallback::Missing => "runtime-missing",
            Fallback::Invalid(_) => "runtime-invalid",
            Fallback::Unapproved => "unapproved",
            Fallback::Denied => "denied",
        }
    }

    /// The note under the poster.
    fn note(&self, r: &str) -> String {
        let why = match self {
            Fallback::Missing => "is not installed",
            Fallback::Invalid(_) => "did not pass validation",
            Fallback::Unapproved | Fallback::Denied => "was not approved by the author",
        };
        format!("Interactive version not included in this copy: runtime {r} {why}.")
    }

    /// The export warning for the runtime and the widgets it affects.
    fn warning(&self, r: &str, ids: &str) -> String {
        match self {
            Fallback::Missing => format!(
                "runtime {r} is not installed in this project (no {}/{r}/{}): {ids} export as posters only.",
                crate::runtimes::RUNTIMES_DIR,
                crate::runtimes::MANIFEST
            ),
            Fallback::Invalid(reason) => {
                format!("runtime {r} is invalid ({reason}): {ids} export as posters only.")
            }
            Fallback::Unapproved => format!(
                "runtime {r} is not approved in this project: {ids} export as posters only. Approve it in {} and export again.",
                crate::widget_approval::PANEL
            ),
            Fallback::Denied => format!(
                "runtime {r} is denied in this project: {ids} export as posters only. Allow it in {} to export it live.",
                crate::widget_approval::PANEL
            ),
        }
    }
}

/// A custom runtime as this export found it.
enum RuntimeUse {
    Unusable(Fallback),
    Valid(Box<ValidRuntime>),
}

/// A valid package: the snapshot that was hashed (and judged), its
/// manifest, and why its widgets do not run live, if they do not.
struct ValidRuntime {
    snap: crate::widget_approval::RuntimeSnapshot,
    manifest: crate::runtimes::RuntimeManifest,
    verdict: Option<Fallback>,
}

/// A custom widget's folded document and bound options, both absent when
/// it falls back to its poster.
type CustomPlan = (Option<String>, Option<Map<String, Value>>);

impl Plan<'_> {
    fn warn(&mut self, kind: BundleWarningKind, message: String) {
        self.warnings.push(BundleWarning { kind, message });
    }

    /// Runtime `r` read once for this export, judged unless previewing.
    fn runtime(&mut self, r: &str) -> Result<std::rc::Rc<RuntimeUse>, String> {
        if let Some(u) = self.runtimes.get(r) {
            return Ok(u.clone());
        }
        let users = self.users.get(r).cloned().unwrap_or_default();
        let checked = match self.gate {
            Gate::Approvals(base) | Gate::Article(base) => {
                crate::widget_approval::check_runtime_at(base, self.cx, self.root_id, r, &users)
                    .map(|c| (c.snapshot, c.status))
            }
            Gate::Preview => crate::widget_approval::snapshot_runtime(self.cx, self.root_id, r)
                .map(|s| (s, None)),
        };
        let used = match checked {
            Err(_) => RuntimeUse::Unusable(Fallback::Missing),
            Ok((snap, status)) => match snap.manifest.clone() {
                None => {
                    let reason = snap.invalid.clone().unwrap_or_default();
                    let reason = reason
                        .strip_prefix(&format!("runtime {r}: "))
                        .map(str::to_string)
                        .unwrap_or(reason);
                    RuntimeUse::Unusable(Fallback::Invalid(reason))
                }
                Some(manifest) => {
                    use crate::widget_approval::WidgetApprovalStatus as S;
                    let verdict = match (self.gate, status) {
                        (Gate::Preview, _) => None,
                        (_, Some(S::Approved(_))) => None,
                        (_, Some(S::ApprovalRequired(a)))
                            if a.cause == maleficium_events::WidgetApprovalCause::Revoked =>
                        {
                            Some(Fallback::Denied)
                        }
                        (_, _) => Some(Fallback::Unapproved),
                    };
                    RuntimeUse::Valid(Box::new(ValidRuntime {
                        snap,
                        manifest,
                        verdict,
                    }))
                }
            },
        };
        let used = std::rc::Rc::new(used);
        self.runtimes.insert(r.to_string(), used.clone());
        Ok(used)
    }

    fn fall_back(&mut self, r: &str, id: &str, why: Fallback) {
        self.notes.insert(id.to_string(), why.note(r));
        self.fallbacks
            .entry(r.to_string())
            .or_insert_with(|| (why, Vec::new()))
            .1
            .push(id.to_string());
    }

    /// A project file named relative to the main file's folder: resolved
    /// inside the root (symlinks that escape are refused) and a regular file.
    fn local(&self, widget: &str, rel: &str) -> Result<(PathBuf, String), String> {
        let joined = self.main_dir_rel.join(rel);
        let canon = crate::fs::resolve_in(self.cx, self.root_id, &joined.to_string_lossy())
            .map_err(|e| format!("widget {widget}: {rel}: {e}"))?;
        if !canon.is_file() {
            return Err(format!("widget {widget}: {rel} is not a file"));
        }
        let source = canon
            .strip_prefix(&self.root)
            .map_err(|_| format!("widget {widget}: {rel} is outside the project"))?
            .to_string_lossy()
            .replace('\\', "/");
        Ok((canon, source))
    }

    fn mode_for(&self, inline_opt: bool) -> Mode {
        if self.profile == BundleProfile::SingleFile || inline_opt {
            Mode::Inline
        } else {
            Mode::Bundled
        }
    }

    fn insert(&mut self, key: String, a: Asset) -> Result<(), String> {
        if self.assets.insert(key.clone(), a).is_some() {
            return Err(format!("two assets would be keyed `{key}`"));
        }
        Ok(())
    }

    fn add_local(
        &mut self,
        key: String,
        widget: &str,
        rel: &str,
        inline_opt: bool,
    ) -> Result<(), String> {
        let (canon, source) = self.local(widget, rel)?;
        let (sha, bytes) = hash_file(&canon)?;
        let ext = safe_ext(rel);
        let a = Asset {
            mode: self.mode_for(inline_opt),
            mime: fold::mime_for(&ext).to_string(),
            sha,
            bytes,
            ext,
            source: Some(source),
            url: None,
            data: Bytes::File(canon),
        };
        self.insert(key, a)
    }

    fn add_mem(
        &mut self,
        key: String,
        ext: &str,
        data: Vec<u8>,
        inline_opt: bool,
    ) -> Result<(), String> {
        let a = Asset {
            mode: self.mode_for(inline_opt),
            mime: fold::mime_for(ext).to_string(),
            sha: sha_of(&data),
            bytes: data.len() as u64,
            ext: ext.to_string(),
            source: None,
            url: None,
            data: Bytes::Mem(data),
        };
        self.insert(key, a)
    }

    /// A remote asset: hashed from the local copy when there is one. With no
    /// local copy the hash needs a download, which is refused unless this
    /// export carries the user's approval for that url.
    fn add_remote(
        &mut self,
        key: String,
        widget: &str,
        role: &str,
        url: &str,
        local: Option<&str>,
        declared_sha: Option<&str>,
    ) -> Result<(), String> {
        if !url.starts_with("https://") || url.len() < 9 {
            return Err(format!(
                "widget {widget}: remote asset {role} must be an https url, not `{url}`"
            ));
        }
        let ext = safe_ext(url.split(['?', '#']).next().unwrap_or(url));
        let (sha, bytes, source) = match local {
            Some(rel) => {
                let (canon, source) = self.local(widget, rel)?;
                let (sha, bytes) = hash_file(&canon)?;
                (sha, bytes, Some(source))
            }
            None => {
                if !self.opts.approved_fetch.iter().any(|u| u == url) {
                    return Err(format!(
                        "widget {widget}: remote asset {role} ({url}) has no local copy, so hashing it needs a download. Maleficium does not fetch on its own: the user has to approve downloading that url for this export, and an agent cannot grant it. Put a local copy of the file next to the paper, or approve the download in the app."
                    ));
                }
                let Some(f) = self.opts.fetcher else {
                    return Err(format!(
                        "widget {widget}: remote asset {role} ({url}) was approved for download, but this build has no downloader"
                    ));
                };
                let data = f.fetch(url)?;
                (sha_of(&data), data.len() as u64, None)
            }
        };
        if let Some(d) = declared_sha {
            if !d.eq_ignore_ascii_case(&sha) {
                return Err(format!(
                    "widget {widget}: sha256 {d} does not match the {role} file (computed {sha})"
                ));
            }
        }
        let a = Asset {
            mode: Mode::Remote,
            mime: fold::mime_for(&ext).to_string(),
            sha,
            bytes,
            ext,
            source,
            url: Some(url.to_string()),
            data: Bytes::None,
        };
        self.insert(key, a)
    }
}

fn json_number_or_string(v: &str) -> Value {
    if !v.is_empty() && v.len() < 15 && v.bytes().all(|c| c.is_ascii_digit()) {
        v.parse::<u64>().map_or_else(|_| v.into(), Value::from)
    } else {
        v.into()
    }
}

/// The rendered region of a page, as a PNG: what a table's typeset rows look
/// like in the pdf of record.
fn crop_png(pdf: &hayro::hayro_syntax::Pdf, page: u32, r: &WidgetRect) -> Result<Vec<u8>, String> {
    use hayro::vello_cpu::color::palette::css::WHITE;
    use hayro::vello_cpu::Pixmap;
    std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| {
        let p = &pdf.pages()[page as usize - 1];
        let (_, page_h) = p.render_dimensions();
        let width_pt = ((r.x1 - r.x0) as f32).max(1.0);
        let scale = 2.0f32.min(1600.0 / width_pt);
        let settings = hayro::RenderSettings {
            x_scale: scale,
            y_scale: scale,
            bg_color: WHITE,
            ..Default::default()
        };
        let full = hayro::render(
            p,
            &hayro::RenderCache::new(),
            &hayro::hayro_interpret::InterpreterSettings::default(),
            &settings,
        );
        let (w, h) = (full.width() as usize, full.height() as usize);
        let px = |v: f32, hi: usize| ((v * scale).max(0.0) as usize).min(hi);
        let (x0, x1) = (
            px(r.x0 as f32, w),
            (((r.x1 as f32) * scale).ceil() as usize).min(w),
        );
        let (y0, y1) = (
            px(page_h - r.y1 as f32, h),
            (((page_h - r.y0 as f32) * scale).ceil() as usize).min(h),
        );
        if x1 <= x0 || y1 <= y0 {
            return Err(format!("the widget's rect lies outside page {page}"));
        }
        let mut buf = Vec::with_capacity((x1 - x0) * (y1 - y0));
        for row in y0..y1 {
            buf.extend_from_slice(&full.data()[row * w + x0..row * w + x1]);
        }
        Pixmap::from_parts(buf, (x1 - x0) as u16, (y1 - y0) as u16)
            .into_png()
            .map_err(|e| format!("cannot encode the table crop: {e}"))
    }))
    .map_err(|_| format!("the renderer failed on page {page}"))?
}

/// The generated host document of a built-in runtime this build ships.
pub(crate) fn runtime_host(runtime: &str) -> Option<&'static str> {
    match runtime {
        "table@1" => Some(TABLE_HOST),
        "chart@1" => Some(CHART_HOST),
        "model@1" => Some(MODEL_HOST),
        "video@1" => Some(VIDEO_HOST),
        _ => None,
    }
}

/// A widget's local sources keyed by role; a repeated role gets `-2`,
/// `-3`, ... in document order.
pub(crate) fn role_keys(w: &Widget) -> Result<Vec<(String, &WidgetSource)>, String> {
    let mut seen: BTreeMap<&str, u32> = BTreeMap::new();
    let mut out = Vec::new();
    for s in &w.sources {
        if s.role.is_empty()
            || !s
                .role
                .bytes()
                .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit())
        {
            return Err(format!(
                "widget {}: source role `{}` is not a plain word",
                w.id, s.role
            ));
        }
        let n = seen.entry(&s.role).or_insert(0);
        *n += 1;
        let key = if *n == 1 {
            s.role.clone()
        } else {
            format!("{}-{}", s.role, n)
        };
        out.push((key, s));
    }
    Ok(out)
}

/// The options a runtime receives: everything but the export-only keys,
/// digits as numbers.
pub(crate) fn runtime_options(w: &Widget) -> Map<String, Value> {
    w.options
        .iter()
        .filter(|o| {
            !matches!(o.key.as_str(), "remote" | "sha256" | "inline")
                && !crate::widgets::ORIGIN_OPTIONS.contains(&o.key.as_str())
        })
        .map(|o| (o.key.clone(), json_number_or_string(&o.value)))
        .collect()
}

/// The licence notice a folded runtime document ends with: the runtime and
/// each vendored library, name, version, licence and licence text, in one
/// HTML comment that no text can close (every `--` is split).
fn licence_block(
    m: &crate::runtimes::RuntimeManifest,
    files: &BTreeMap<String, Vec<u8>>,
) -> String {
    let text = |p: &str| {
        files
            .get(p)
            .map(|b| String::from_utf8_lossy(b).into_owned())
            .unwrap_or_default()
    };
    let mut body = format!(
        "\n{} {} ({})\n{}",
        m.name,
        m.version,
        m.license,
        text("LICENSE")
    );
    for v in &m.vendored {
        body.push_str(&format!(
            "\n{} {} ({})\n{}",
            v.name,
            v.version,
            v.license,
            text(&v.license_file)
        ));
    }
    let mut safe = String::with_capacity(body.len());
    for c in body.chars() {
        if c == '-' && safe.ends_with('-') {
            safe.push(' ');
        }
        safe.push(c);
    }
    format!("<!-- Licences:{safe} -->")
}

/// A custom widget with no usable poster whose map still names one: its
/// poster was rendered for an older state (often a changed runtime
/// digest). The export keeps the placeholder and says so; it never refuses.
fn stale_custom_poster(p: &Plan, w: &Widget) -> Option<String> {
    use crate::widgets::poster::cache::{custom_key_now_at, map_key_for};
    let base = match p.gate {
        Gate::Approvals(base) | Gate::Article(base) => base,
        Gate::Preview => return None,
    };
    let r = w.runtime.as_deref().unwrap_or("");
    let mapped = map_key_for(p.cx, p.root_id, p.main_rel, &w.id)?;
    let (now, _) = custom_key_now_at(base, p.cx, p.root_id, p.main_rel, w, p.theme)?;
    (mapped != now).then(|| {
        format!(
            "widget {}: its poster was rendered for an older state of runtime {r}; it shows a placeholder until the next compile renders it.",
            w.id
        )
    })
}

/// A custom widget: its runtime read and judged once per export, bound
/// (an error refuses the export), then folded live with its sources, or
/// left to its poster with a note. Returns the document and the bound
/// options when live.
fn plan_custom(
    p: &mut Plan,
    w: &Widget,
    sources: &mut Map<String, Value>,
) -> Result<CustomPlan, String> {
    let id = w.id.clone();
    let r = w.runtime.clone().unwrap_or_default();
    let used = p.runtime(&r)?;
    let (snap, m, verdict) = match &*used {
        RuntimeUse::Unusable(why) => {
            p.fall_back(&r, &id, why.clone());
            return Ok((None, None));
        }
        RuntimeUse::Valid(v) => (&v.snap, &v.manifest, &v.verdict),
    };
    let bound = crate::runtimes::bind(w, m)?;
    if let Some(why) = verdict {
        p.fall_back(&r, &id, why.clone());
        return Ok((None, None));
    }
    // A live declaring widget runs srcdoc'd under the single-file reader
    // page: the page's own policy must carry the token, or the inherited
    // one blocks the compile. Folder widgets are documents of their own.
    if m.capabilities.wasm {
        p.wasm_live = true;
    }
    for (role, s) in &bound.sources {
        let key = format!("{id}-{role}");
        p.add_local(key.clone(), &id, &s.path, false)?;
        let bytes = p.assets.get(&key).map_or(0, |a| a.bytes);
        crate::runtimes::check_size(w, m, role, bytes)?;
        sources.insert(role.clone(), key.into());
    }
    // The judged snapshot's files, never a second read of the folder,
    // folded with the runtime's own policy: only a runtime that declared
    // capabilities.wasm carries 'wasm-unsafe-eval'.
    let fold_input: BTreeMap<String, Vec<u8>> = snap
        .files
        .iter()
        .filter(|(path, _)| !m.is_metadata(path))
        .map(|(k, v)| (k.clone(), v.clone()))
        .collect();
    let folded = fold::fold_bundle(
        &fold_input,
        &fold::widget_policy_for(None, m.capabilities.wasm),
    )
    .map_err(|e| format!("widget {id}: runtime {r}: {e}"))?;
    if !folded.unfolded.is_empty() {
        let shown: Vec<_> = folded.unfolded.iter().take(8).cloned().collect();
        let more = folded.unfolded.len() - shown.len();
        p.warn(
            BundleWarningKind::UnfoldedFiles,
            format!(
                "widget {id}: runtime {r} files not inlined, so a page that fetches them at run time will not find them: {}{}",
                shown.join(", "),
                if more > 0 { format!(" and {more} more") } else { String::new() }
            ),
        );
    }
    for e in &folded.external {
        p.warn(
            BundleWarningKind::ExternalReference,
            format!("widget {id}: runtime {r} references {e}, which its policy blocks"),
        );
    }
    for n in &folded.notes {
        p.warn(
            BundleWarningKind::FoldLimit,
            format!("widget {id}: runtime {r}: {n}"),
        );
    }
    let doc = folded.html + &licence_block(m, &snap.files);
    p.runtime_entries.insert(
        r.clone(),
        json!({
            "name": m.name,
            "version": m.version,
            "digest": snap.digest,
            "license": m.license,
            "capabilities": { "webgl": m.capabilities.webgl, "wasm": m.capabilities.wasm },
            "vendored": m.vendored.iter().map(|v| json!({
                "name": v.name, "version": v.version, "license": v.license
            })).collect::<Vec<_>>(),
        }),
    );
    Ok((Some(doc), Some(bound.options)))
}

fn plan_widget(
    p: &mut Plan,
    w: &Widget,
    pdf: &hayro::hayro_syntax::Pdf,
    pdf_pages: u32,
) -> Result<Planned, String> {
    let id = w.id.clone();
    if w.page < 1 || w.page > pdf_pages {
        return Err(format!(
            "widget {id}: page {} is outside the pdf's {pdf_pages} pages",
            w.page
        ));
    }
    let mb = pdf.pages()[w.page as usize - 1].media_box();
    let slack = 1.0;
    if w.rect.x0 >= w.rect.x1
        || w.rect.y0 >= w.rect.y1
        || w.rect.x0 < mb.x0 - slack
        || w.rect.y0 < mb.y0 - slack
        || w.rect.x1 > mb.x1 + slack
        || w.rect.y1 > mb.y1 + slack
    {
        return Err(format!(
            "widget {id}: its rect lies outside the media box of page {}",
            w.page
        ));
    }
    let inline_opt = option(w, "inline").is_some_and(truthy);
    let remote = option(w, "remote").filter(|r| !r.is_empty());
    if remote.is_some() && w.kind != WidgetType::Video {
        return Err(format!(
            "widget {id}: remote= is only supported on video widgets"
        ));
    }

    // The poster is what the pdf shows: the document's own, else the
    // cached auto-poster, else (a table's typeset rows, a placeholder)
    // cropped from the pdf. The cache is read against the same approval
    // store the export judges runtimes by, so an isolated store (tests,
    // the article) sees its own posters.
    let poster_key = format!("{id}-poster");
    let cached = match p.gate {
        Gate::Approvals(base) | Gate::Article(base) => {
            crate::widgets::poster::cache::cached_poster_at(
                base, p.cx, p.root_id, p.main_rel, w, p.theme,
            )
        }
        Gate::Preview => {
            crate::widgets::poster::cache::cached_poster(p.cx, p.root_id, p.main_rel, w, p.theme)
        }
    };
    let source = crate::widgets::poster::poster_source(w, cached.as_deref());
    match source {
        PosterSource::Explicit(rel) if w.kind != WidgetType::Table => {
            p.add_local(poster_key.clone(), &id, &rel, inline_opt)?
        }
        PosterSource::Cached(png) => {
            let name = png.file_name().map(|n| n.to_string_lossy().into_owned());
            let rel = Path::new(crate::widgets::poster::cache::CACHE_DIR)
                .join(crate::widgets::poster::cache::POSTERS_DIR)
                .join(name.unwrap_or_default());
            p.add_local(poster_key.clone(), &id, &rel.to_string_lossy(), inline_opt)?
        }
        _ => {
            if w.kind == WidgetType::Custom {
                if let Some(msg) = stale_custom_poster(p, w) {
                    p.warn(BundleWarningKind::RuntimeDigestChanged, msg);
                }
            }
            let png = crop_png(pdf, w.page, &w.rect).map_err(|e| format!("widget {id}: {e}"))?;
            p.add_mem(poster_key.clone(), "png", png, inline_opt)?;
        }
    }

    let mut sources = Map::new();
    // A widget's declared origins come from the snapshot whose files are
    // folded, never from an earlier read: the policy and the code match.
    let mut csp: Option<crate::widgets::WidgetCsp> = None;
    // A live custom widget's bound options.
    let mut custom_options: Option<Map<String, Value>> = None;

    let doc: Option<String> = if w.kind == WidgetType::Html {
        let target = crate::widget_approval::WidgetTarget::of(p.main_rel, w)?
            .ok_or_else(|| format!("widget {id}: an html widget has no bundle folder"))?;
        let snap = crate::widget_approval::snapshot(p.cx, p.root_id, &target)?;
        csp = (!snap.origins.is_empty()).then(|| snap.origins.clone());
        let policy = fold::widget_policy(csp.as_ref());
        let folded =
            fold::fold_bundle(&snap.files, &policy).map_err(|e| format!("widget {id}: {e}"))?;
        if !folded.unfolded.is_empty() {
            let shown: Vec<_> = folded.unfolded.iter().take(8).cloned().collect();
            let more = folded.unfolded.len() - shown.len();
            p.warn(
                BundleWarningKind::UnfoldedFiles,
                format!(
                    "widget {id}: files not inlined, so a page that fetches them at run time will not find them: {}{}",
                    shown.join(", "),
                    if more > 0 { format!(" and {more} more") } else { String::new() }
                ),
            );
        }
        for e in &folded.external {
            p.warn(
                BundleWarningKind::ExternalReference,
                format!("widget {id}: references {e}, which its policy blocks unless widget.json declares the origin"),
            );
        }
        for n in &folded.notes {
            p.warn(BundleWarningKind::FoldLimit, format!("widget {id}: {n}"));
        }
        // The in-app article holds back what the user has not approved: the
        // figure keeps its poster with an approval affordance, and the folded
        // document is left out. Exports and the browser preview run it.
        let held_back = match p.gate {
            Gate::Article(base) => crate::widget_approval::check_at(base, p.cx, p.root_id, &target)
                .map(|c| !c.status.is_approved())
                .unwrap_or(true),
            _ => false,
        };
        if held_back {
            p.notes.insert(
                id.clone(),
                "This interactive figure needs your approval before it runs here.".to_string(),
            );
            p.gated.insert(id.clone());
            None
        } else {
            Some(folded.html)
        }
    } else if w.kind == WidgetType::Custom {
        let (doc, options) = plan_custom(p, w, &mut sources)?;
        custom_options = options;
        doc
    } else {
        let mut video_local: Option<&str> = None;
        for (role_key, s) in role_keys(w)? {
            if w.kind == WidgetType::Video && s.role == "video" && remote.is_some() {
                video_local = Some(&s.path);
                continue;
            }
            let key = format!("{id}-{role_key}");
            p.add_local(key.clone(), &id, &s.path, inline_opt)?;
            sources.insert(role_key, key.into());
        }
        if let Some(url) = remote {
            let key = format!("{id}-video");
            p.add_remote(
                key.clone(),
                &id,
                "video",
                url,
                video_local,
                option(w, "sha256").filter(|s| !s.is_empty()),
            )?;
            sources.insert("video".into(), key.into());
        }
        let required = match w.kind {
            WidgetType::Model => Some("model"),
            WidgetType::Video => Some("video"),
            WidgetType::Table => Some("data"),
            WidgetType::Chart => Some("spec"),
            WidgetType::Html | WidgetType::Custom => None,
        };
        if let Some(role) = required {
            if !sources.contains_key(role) {
                return Err(format!("widget {id}: it records no {role} source"));
            }
        }
        let runtime = w.runtime.as_deref().unwrap_or("");
        let host = runtime_host(runtime)
            .ok_or_else(|| format!("widget {id}: no {runtime} runtime in this build"))?;
        Some(fold::with_policy(host, &fold::widget_policy(None)))
    };
    let entry = (p.profile != BundleProfile::SingleFile && doc.is_some())
        .then(|| format!("widgets/{id}/index.html"));

    let mut j = Map::new();
    j.insert("id".into(), id.clone().into());
    j.insert(
        "type".into(),
        serde_json::to_value(w.kind).map_err(|e| e.to_string())?,
    );
    if w.kind != WidgetType::Html {
        j.insert("runtime".into(), w.runtime.clone().into());
    }
    if let Some(e) = entry {
        j.insert("entry".into(), e.into());
    }
    j.insert("page".into(), w.page.into());
    j.insert(
        "rect".into(),
        json!([w.rect.x0, w.rect.y0, w.rect.x1, w.rect.y1]),
    );
    if let Some(l) = &w.label {
        j.insert("label".into(), l.clone().into());
    }
    if let Some(f) = &w.figure {
        j.insert("figure".into(), f.clone().into());
    }
    j.insert("poster".into(), poster_key.into());
    j.insert("alt".into(), w.alt.clone().into());
    if w.kind != WidgetType::Html {
        j.insert("sources".into(), Value::Object(sources));
    }
    if w.kind == WidgetType::Custom {
        match custom_options {
            Some(o) => {
                j.insert("options".into(), Value::Object(o));
            }
            None => {
                let r = w.runtime.as_deref().unwrap_or("");
                let why = p.fallbacks.get(r).map_or("", |(f, _)| f.name());
                j.insert("fallback".into(), why.into());
            }
        }
    } else {
        let opts = runtime_options(w);
        if !opts.is_empty() {
            j.insert("options".into(), Value::Object(opts));
        }
    }
    if let Some(c) = &csp {
        j.insert(
            "csp".into(),
            serde_json::to_value(c).map_err(|e| e.to_string())?,
        );
    }
    Ok(Planned {
        json: Value::Object(j),
        id,
        doc,
        frames: csp.map(|c| c.frame_domains).unwrap_or_default(),
    })
}

